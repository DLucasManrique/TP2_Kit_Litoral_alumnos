DROP TABLE detalle_pedido CASCADE CONSTRAINTS;
DROP TABLE pedido         CASCADE CONSTRAINTS;
DROP TABLE producto       CASCADE CONSTRAINTS;
DROP TABLE categoria      CASCADE CONSTRAINTS;
DROP TABLE cliente        CASCADE CONSTRAINTS;

CREATE TABLE categoria (
    id_categoria  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR2(60) NOT NULL,
    CONSTRAINT uq_categoria_nombre UNIQUE (nombre)
);

CREATE TABLE cliente (
    id_cliente    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni           VARCHAR2(10)  NOT NULL,
    nombre        VARCHAR2(60)  NOT NULL,
    apellido      VARCHAR2(60)  NOT NULL,
    email         VARCHAR2(120),
    ciudad        VARCHAR2(60),
    activo        CHAR(1) DEFAULT 'S' NOT NULL,
    fecha_alta    DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uq_cliente_dni    UNIQUE (dni),
    CONSTRAINT ck_cliente_activo CHECK (activo IN ('S','N'))
);

COMMENT ON COLUMN cliente.activo IS 'Baja lógica: los clientes NUNCA se borran, se marcan con N';

CREATE TABLE producto (
    id_producto   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR2(100) NOT NULL,
    precio        NUMBER(10,2)  NOT NULL,
    stock         NUMBER(6) DEFAULT 0 NOT NULL,
    id_categoria  NUMBER(10) NOT NULL,
    CONSTRAINT ck_producto_precio CHECK (precio > 0),
    CONSTRAINT ck_producto_stock  CHECK (stock >= 0),
    CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria)
        REFERENCES categoria (id_categoria)
);

CREATE TABLE pedido (
    id_pedido     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha         DATE DEFAULT SYSDATE NOT NULL,
    estado        VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL,
    id_cliente    NUMBER(10) NOT NULL,
    CONSTRAINT ck_pedido_estado CHECK (estado IN ('PENDIENTE','ENTREGADO','CANCELADO')),
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente)
);

CREATE TABLE detalle_pedido (
    id_detalle_pedido NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido         NUMBER(10) NOT NULL,
    id_producto       NUMBER(10) NOT NULL,
    cantidad          NUMBER(5)  NOT NULL,
    precio_unitario   NUMBER(10,2) NOT NULL,
    CONSTRAINT uq_detalle_pedido_producto UNIQUE (id_pedido, id_producto),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT fk_detalle_pedido   FOREIGN KEY (id_pedido)
        REFERENCES pedido (id_pedido),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto)
);
